import { pgTable, text, boolean, integer, date, timestamp, uuid, uniqueIndex, index, check, primaryKey, type AnyPgColumn } from "drizzle-orm/pg-core";
import { sql } from "drizzle-orm";
import { pk, fkCol, halalas, qty, createdAt, updatedAt, memberFk } from "./_helpers";
import { branches } from "./core";
import { rooms } from "./academic";
import { departments } from "./hr";
import { otpChallenges } from "./security";

export const itemCategories = pgTable("item_categories", {
  id: pk(),
  parentId: fkCol("parent_id").references((): AnyPgColumn => itemCategories.id),
  code: text("code").notNull(),
  name: text("name").notNull(),
}, (t) => [uniqueIndex("item_categories_code_uq").on(t.code)]);

export const units = pgTable("units", {
  id: pk(),
  code: text("code").notNull(),
  name: text("name").notNull(),
}, (t) => [uniqueIndex("units_code_uq").on(t.code)]);

/** Item master. item_code is generated by the application with next_doc_no('ITM') / category prefix and never reused. */
export const items = pgTable("items", {
  id: pk(),
  itemCode: text("item_code").notNull(),
  name: text("name").notNull(),
  categoryId: fkCol("category_id").notNull().references(() => itemCategories.id),
  unitId: fkCol("unit_id").notNull().references(() => units.id),
  itemType: text("item_type").notNull().default("consumable"),
  valuationMethod: text("valuation_method").notNull().default("weighted_average"),
  description: text("description"),
  isActive: boolean("is_active").notNull().default(true),
  createdBy: memberFk("created_by"),
  createdAt: createdAt(),
  updatedAt: updatedAt(),
}, (t) => [
  uniqueIndex("items_code_uq").on(t.itemCode),
  index("items_category_idx").on(t.categoryId),
  check("items_type_ck", sql`${t.itemType} in ('consumable','asset','service')`),
  check("items_valuation_ck", sql`${t.valuationMethod} in ('weighted_average','fifo')`),
]);

/** Each branch has its own warehouse (business decision); the head office may have more than one. */
export const warehouses = pgTable("warehouses", {
  id: pk(),
  branchId: fkCol("branch_id").notNull().references(() => branches.id),
  code: text("code").notNull(),
  name: text("name").notNull(),
  keeperMemberId: memberFk("keeper_member_id"),
  status: text("status").notNull().default("active"),
  createdAt: createdAt(),
}, (t) => [
  uniqueIndex("warehouses_code_uq").on(t.code),
  index("warehouses_branch_idx").on(t.branchId),
  check("warehouses_status_ck", sql`${t.status} in ('active','inactive')`),
]);

/** Reorder policy per item and warehouse; the manager sets min_qty, the system may suggest it (usage x lead time + safety). */
export const stockLevels = pgTable("stock_levels", {
  warehouseId: fkCol("warehouse_id").notNull().references(() => warehouses.id),
  itemId: fkCol("item_id").notNull().references(() => items.id),
  minQty: qty("min_qty").notNull(),
  maxQty: qty("max_qty"),
  reorderQty: qty("reorder_qty"),
  leadTimeDays: integer("lead_time_days"),
  setBy: memberFk("set_by"),
  updatedAt: updatedAt(),
}, (t) => [
  primaryKey({ columns: [t.warehouseId, t.itemId] }),
  check("stock_levels_qty_ck", sql`${t.minQty} >= 0 and (${t.maxQty} is null or ${t.maxQty} >= ${t.minQty}) and (${t.reorderQty} is null or ${t.reorderQty} > 0)`),
]);

/**
 * Append-only stock ledger. Balance = SUM(qty_delta) (view v_stock_balances). UPDATE/DELETE are blocked by trigger and a
 * trigger refuses any movement that would drive a balance negative. Opening balances are movements of type 'opening'.
 */
export const stockMovements = pgTable("stock_movements", {
  id: pk(),
  movementNo: text("movement_no").notNull(),
  warehouseId: fkCol("warehouse_id").notNull().references(() => warehouses.id),
  itemId: fkCol("item_id").notNull().references(() => items.id),
  movementType: text("movement_type").notNull(),
  qtyDelta: qty("qty_delta").notNull(),
  unitCostHalalas: halalas("unit_cost_halalas"),
  occurredAt: timestamp("occurred_at", { withTimezone: true }).defaultNow().notNull(),
  refType: text("ref_type"),
  refId: fkCol("ref_id"),
  issuedToRoomId: fkCol("issued_to_room_id").references(() => rooms.id),
  issuedToDepartmentId: fkCol("issued_to_department_id").references(() => departments.id),
  purpose: text("purpose"),
  createdBy: memberFk("created_by").notNull(),
  otpChallengeId: uuid("otp_challenge_id").references(() => otpChallenges.id),
  createdAt: createdAt(),
}, (t) => [
  uniqueIndex("stock_movements_no_uq").on(t.movementNo),
  index("stock_movements_wh_item_idx").on(t.warehouseId, t.itemId, t.occurredAt),
  index("stock_movements_room_idx").on(t.issuedToRoomId, t.occurredAt).where(sql`${t.issuedToRoomId} is not null`),
  check("stock_movements_type_ck", sql`${t.movementType} in ('opening','receipt','issue','transfer_out','transfer_in','adjustment','return_to_supplier','return_from_room')`),
  check("stock_movements_delta_ck", sql`${t.qtyDelta} <> 0`),
  check("stock_movements_sign_ck", sql`(${t.movementType} in ('opening','receipt','transfer_in','return_from_room') and ${t.qtyDelta} > 0) or (${t.movementType} in ('issue','transfer_out','return_to_supplier') and ${t.qtyDelta} < 0) or ${t.movementType} = 'adjustment'`),
  check("stock_movements_issue_target_ck", sql`${t.movementType} <> 'issue' or ${t.issuedToRoomId} is not null or ${t.issuedToDepartmentId} is not null`),
  check("stock_movements_cost_ck", sql`${t.unitCostHalalas} is null or ${t.unitCostHalalas} >= 0`),
]);

export const stockTransfers = pgTable("stock_transfers", {
  id: pk(),
  transferNo: text("transfer_no").notNull(),
  fromWarehouseId: fkCol("from_warehouse_id").notNull().references(() => warehouses.id),
  toWarehouseId: fkCol("to_warehouse_id").notNull().references(() => warehouses.id),
  status: text("status").notNull().default("draft"),
  requestedBy: memberFk("requested_by").notNull(),
  shippedAt: timestamp("shipped_at", { withTimezone: true }),
  receivedAt: timestamp("received_at", { withTimezone: true }),
  createdAt: createdAt(),
}, (t) => [
  uniqueIndex("stock_transfers_no_uq").on(t.transferNo),
  check("stock_transfers_wh_ck", sql`${t.fromWarehouseId} <> ${t.toWarehouseId}`),
  check("stock_transfers_status_ck", sql`${t.status} in ('draft','in_transit','received','cancelled')`),
]);

export const stockTransferLines = pgTable("stock_transfer_lines", {
  transferId: fkCol("transfer_id").notNull().references(() => stockTransfers.id, { onDelete: "cascade" }),
  itemId: fkCol("item_id").notNull().references(() => items.id),
  qty: qty("qty").notNull(),
  receivedQty: qty("received_qty"),
}, (t) => [primaryKey({ columns: [t.transferId, t.itemId] }), check("stock_transfer_lines_qty_ck", sql`${t.qty} > 0 and (${t.receivedQty} is null or ${t.receivedQty} >= 0)`)]);

/** Physical stock-taking; differences are posted as 'adjustment' movements with a mandatory reason. */
export const stockCounts = pgTable("stock_counts", {
  id: pk(),
  warehouseId: fkCol("warehouse_id").notNull().references(() => warehouses.id),
  countDate: date("count_date", { mode: "string" }).notNull(),
  status: text("status").notNull().default("open"),
  countedBy: memberFk("counted_by").notNull(),
  closedAt: timestamp("closed_at", { withTimezone: true }),
}, (t) => [check("stock_counts_status_ck", sql`${t.status} in ('open','closed','cancelled')`)]);

export const stockCountLines = pgTable("stock_count_lines", {
  countId: fkCol("count_id").notNull().references(() => stockCounts.id, { onDelete: "cascade" }),
  itemId: fkCol("item_id").notNull().references(() => items.id),
  systemQty: qty("system_qty").notNull(),
  countedQty: qty("counted_qty").notNull(),
  reason: text("reason"),
}, (t) => [primaryKey({ columns: [t.countId, t.itemId] }), check("stock_count_lines_ck", sql`${t.countedQty} >= 0 and (${t.countedQty} = ${t.systemQty} or ${t.reason} is not null)`)]);

/** One open alert per item and warehouse at a time (partial unique index) so procurement is never spammed. */
export const reorderAlerts = pgTable("reorder_alerts", {
  id: pk(),
  warehouseId: fkCol("warehouse_id").notNull().references(() => warehouses.id),
  itemId: fkCol("item_id").notNull().references(() => items.id),
  qtyAtTrigger: qty("qty_at_trigger").notNull(),
  minQty: qty("min_qty").notNull(),
  status: text("status").notNull().default("open"),
  openedAt: timestamp("opened_at", { withTimezone: true }).defaultNow().notNull(),
  escalatedAt: timestamp("escalated_at", { withTimezone: true }),
  closedAt: timestamp("closed_at", { withTimezone: true }),
  purchaseRequestId: fkCol("purchase_request_id"),                       // FK added in procurement.ts
}, (t) => [
  uniqueIndex("reorder_alerts_one_open_uq").on(t.warehouseId, t.itemId).where(sql`${t.status} in ('open','in_progress')`),
  check("reorder_alerts_status_ck", sql`${t.status} in ('open','in_progress','closed','dismissed')`),
]);
